#!/usr/bin/env python3
"""Generate KeyTables.java from constant dumps (javap -constants) of:
   GLFW (LWJGL 3.3.3), SDLScancode and SDLKeycode (LWJGL 3.4.3).
Usage: gen_keytables.py const_GLFW.txt const_SDLScancode.txt const_SDLKeycode.txt > KeyTables.java"""
import sys

def load(path, prefix):
    out = {}
    for line in open(path):
        parts = line.split()
        if len(parts) == 3:
            _, name, val = parts
        elif len(parts) == 2:
            name, val = parts
        else:
            continue
        if name.startswith(prefix):
            out[name[len(prefix):]] = int(val.rstrip('L'))
    return out

glfw = load(sys.argv[1], 'GLFW_KEY_')
sc = load(sys.argv[2], 'SDL_SCANCODE_')
kc = load(sys.argv[3], 'SDLK_')

# GLFW key name -> SDL scancode name (only where they differ)
alias = {
    'APOSTROPHE': 'APOSTROPHE', 'EQUAL': 'EQUALS', 'LEFT_BRACKET': 'LEFTBRACKET',
    'RIGHT_BRACKET': 'RIGHTBRACKET', 'GRAVE_ACCENT': 'GRAVE', 'WORLD_1': 'NONUSBACKSLASH',
    'WORLD_2': 'INTERNATIONAL1', 'ENTER': 'RETURN', 'PAGE_UP': 'PAGEUP', 'PAGE_DOWN': 'PAGEDOWN',
    'CAPS_LOCK': 'CAPSLOCK', 'SCROLL_LOCK': 'SCROLLLOCK', 'NUM_LOCK': 'NUMLOCKCLEAR',
    'PRINT_SCREEN': 'PRINTSCREEN', 'KP_DECIMAL': 'KP_PERIOD', 'KP_SUBTRACT': 'KP_MINUS',
    'KP_ADD': 'KP_PLUS', 'KP_EQUAL': 'KP_EQUALS', 'LEFT_SHIFT': 'LSHIFT', 'LEFT_CONTROL': 'LCTRL',
    'LEFT_ALT': 'LALT', 'LEFT_SUPER': 'LGUI', 'RIGHT_SHIFT': 'RSHIFT', 'RIGHT_CONTROL': 'RCTRL',
    'RIGHT_ALT': 'RALT', 'RIGHT_SUPER': 'RGUI', 'MENU': 'APPLICATION',
}
glfw_to_sc = {}
for name, code in glfw.items():
    if name in ('UNKNOWN', 'LAST') or code < 0:
        continue
    target = alias.get(name, name)
    if target in sc:
        glfw_to_sc[code] = sc[target]
    else:
        print(f'// no SDL scancode for GLFW_KEY_{name}', file=sys.stderr)

sc_to_key = {}
for name, code in sc.items():
    if name in ('UNKNOWN', 'COUNT', 'RESERVED'):
        continue
    if name in kc:
        sc_to_key[code] = kc[name]
    else:
        # SDL rule: keys without a character map to SCANCODE_TO_KEYCODE(sc)
        sc_to_key[code] = code | (1 << 30)

# Scancode names as returned by SDL3's SDL_GetScancodeName (subset; others fall back)
names = {
    'RETURN': 'Return', 'ESCAPE': 'Escape', 'BACKSPACE': 'Backspace', 'TAB': 'Tab', 'SPACE': 'Space',
    'MINUS': '-', 'EQUALS': '=', 'LEFTBRACKET': '[', 'RIGHTBRACKET': ']', 'BACKSLASH': '\\\\',
    'NONUSHASH': '#', 'SEMICOLON': ';', 'APOSTROPHE': "'", 'GRAVE': '`', 'COMMA': ',', 'PERIOD': '.',
    'SLASH': '/', 'CAPSLOCK': 'CapsLock', 'PRINTSCREEN': 'PrintScreen', 'SCROLLLOCK': 'ScrollLock',
    'PAUSE': 'Pause', 'INSERT': 'Insert', 'HOME': 'Home', 'PAGEUP': 'PageUp', 'DELETE': 'Delete',
    'END': 'End', 'PAGEDOWN': 'PageDown', 'RIGHT': 'Right', 'LEFT': 'Left', 'DOWN': 'Down', 'UP': 'Up',
    'NUMLOCKCLEAR': 'Numlock', 'KP_DIVIDE': 'Keypad /', 'KP_MULTIPLY': 'Keypad *',
    'KP_MINUS': 'Keypad -', 'KP_PLUS': 'Keypad +', 'KP_ENTER': 'Keypad Enter', 'KP_PERIOD': 'Keypad .',
    'NONUSBACKSLASH': '', 'APPLICATION': 'Application', 'POWER': 'Power', 'KP_EQUALS': 'Keypad =',
    'MENU': 'Menu', 'MUTE': 'Mute', 'VOLUMEUP': 'VolumeUp', 'VOLUMEDOWN': 'VolumeDown',
    'LCTRL': 'Left Ctrl', 'LSHIFT': 'Left Shift', 'LALT': 'Left Alt', 'LGUI': 'Left GUI',
    'RCTRL': 'Right Ctrl', 'RSHIFT': 'Right Shift', 'RALT': 'Right Alt', 'RGUI': 'Right GUI',
    'MODE': 'ModeSwitch',
}
for i in range(1, 25):
    names[f'F{i}'] = f'F{i}'
for i in range(10):
    names[f'KP_{i}'] = f'Keypad {i}'
for c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789':
    names[c] = c
sc_name = {}
for name, code in sc.items():
    if name in names:
        sc_name[code] = names[name]

def arr(d, size, default='0'):
    vals = [str(d.get(i, default)) for i in range(size)]
    lines = []
    for i in range(0, size, 16):
        lines.append('        ' + ', '.join(vals[i:i+16]) + ',')
    return '\n'.join(lines)

def sarr(d, size):
    vals = ['"' + d[i].replace('"', '\\"') + '"' if i in d else 'null' for i in range(size)]
    lines = []
    for i in range(0, size, 8):
        lines.append('        ' + ', '.join(vals[i:i+8]) + ',')
    return '\n'.join(lines)

print(f'''// GENERATED by tools/gen_keytables.py - do not edit.
package dev.amethyst.sdlshim;

final class KeyTables {{
    private KeyTables() {{}}

    /** GLFW key code (index) -> SDL_Scancode. */
    static final int[] GLFW_TO_SCANCODE = {{
{arr(glfw_to_sc, 349)}
    }};

    /** SDL_Scancode (index) -> SDL_Keycode for a US layout. */
    static final int[] SCANCODE_TO_KEYCODE = {{
{arr(sc_to_key, 512)}
    }};

    /** SDL_Scancode (index) -> SDL_GetScancodeName() result. */
    static final String[] SCANCODE_NAME = {{
{sarr(sc_name, 512)}
    }};
}}''')
